// Helper to generate items for other cafes so every cafe in discovery has a populated menu!
export const generateAllMenuItems = (cafes: Cafe[]): MenuItem[] => {
  const allItems: MenuItem[] = [...SEED_MENU_ITEMS];

  cafes.forEach((cafe, index) => {
    if (cafe.id === 'cafe-1') return; // already has items
    // generate cafe-specific variations with realistic prices
    SEED_MENU_ITEMS.forEach((seedItem, itemIdx) => {
      // Pick 8-12 items per cafe to make 70+ total menu items
      if (itemIdx % 2 === index % 2 || itemIdx < 6) {
        allItems.push({
          ...seedItem,
          id: `item-${cafe.id}-${itemIdx + 1}`,
          cafe_id: cafe.id,
          price: seedItem.price + ((index * 10) % 40) - 20, // subtle realistic variation
        });
      }
    });
  });

  return allItems;
};

